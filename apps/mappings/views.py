from rest_framework import viewsets, status
from rest_framework.response import Response
from rest_framework.permissions import IsAuthenticated
from drf_spectacular.utils import extend_schema, OpenApiParameter

from apps.mappings.serializers import MappingSerializer, MappingCreateSerializer
from apps.mappings.services import MappingService
from apps.mappings.permissions import IsMappingPatientOwner
from common.idempotency.services import idempotent_action


class MappingViewSet(viewsets.ViewSet):
    """
    ViewSet for Patient-Doctor Assignments:
    - View/Assign/Delete restricted strictly to the Patient's Creator.
    - Idempotency enforced on POST /api/mappings/
    """
    permission_classes = [IsAuthenticated, IsMappingPatientOwner]

    @extend_schema(
        responses={200: MappingSerializer(many=True)},
        description="Retrieve all doctor mappings for patients created by the authenticated user."
    )
    def list(self, request):
        mappings = MappingService.list_mappings(user=request.user)
        serializer = MappingSerializer(mappings, many=True)
        return Response({"success": True, "data": serializer.data}, status=status.HTTP_200_OK)

    @extend_schema(
        responses={200: MappingSerializer},
        description="Retrieve a specific doctor mapping (patient creator only)."
    )
    def retrieve(self, request, pk=None):
        mapping = MappingService.get_mapping(user=request.user, mapping_id=int(pk))
        serializer = MappingSerializer(mapping)
        return Response({"success": True, "data": serializer.data}, status=status.HTTP_200_OK)

    @extend_schema(
        parameters=[
            OpenApiParameter(
                name='Idempotency-Key',
                type=str,
                location=OpenApiParameter.HEADER,
                required=True,
                description='Unique key generated by client to ensure retry-safe creation.'
            )
        ],
        request=MappingCreateSerializer,
        responses={201: MappingSerializer},
        description="Assign a doctor to a patient. Patient creator only. Protected by Idempotency-Key."
    )
    @idempotent_action(endpoint='/api/mappings/')
    def create(self, request):
        serializer = MappingCreateSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)

        mapping = MappingService.assign_doctor(
            user=request.user,
            patient_id=serializer.validated_data['patient_id'],
            doctor_id=serializer.validated_data['doctor_id']
        )
        return Response(
            {"success": True, "data": MappingSerializer(mapping).data},
            status=status.HTTP_201_CREATED
        )

    @extend_schema(
        responses={200: None},
        description="Remove doctor assignment from patient (patient creator only)."
    )
    def destroy(self, request, pk=None):
        MappingService.delete_mapping(user=request.user, mapping_id=int(pk))
        return Response(
            {"success": True, "message": "Doctor assignment removed successfully."},
            status=status.HTTP_200_OK
        )
