from rest_framework import viewsets, status
from rest_framework.response import Response
from rest_framework.permissions import IsAuthenticated
from drf_spectacular.utils import extend_schema, OpenApiParameter

from apps.patients.serializers import (
    PatientSerializer,
    PatientCreateSerializer,
    PatientUpdateSerializer
)
from apps.patients.services import PatientService
from apps.patients.permissions import IsPatientCreator
from common.idempotency.services import idempotent_action


class PatientViewSet(viewsets.ViewSet):
    """
    ViewSet handling Patient domain operations:
    - POST: Create with Idempotency-Key protection
    - GET: List/Retrieve with Creator-only authorization
    - PUT/PATCH: Update with Optimistic Locking version checks
    - DELETE: Creator-only deletion
    """
    permission_classes = [IsAuthenticated, IsPatientCreator]

    @extend_schema(
        responses={200: PatientSerializer(many=True)},
        description="Retrieve all patient records created by the authenticated user."
    )
    def list(self, request):
        patients = PatientService.list_patients(user=request.user)
        serializer = PatientSerializer(patients, many=True)
        return Response({"success": True, "data": serializer.data}, status=status.HTTP_200_OK)

    @extend_schema(
        responses={200: PatientSerializer},
        description="Retrieve a single patient record by ID (creator only)."
    )
    def retrieve(self, request, pk=None):
        patient = PatientService.get_patient(user=request.user, patient_id=int(pk))
        self.check_object_permissions(request, patient)
        serializer = PatientSerializer(patient)
        return Response({"success": True, "data": serializer.data}, status=status.HTTP_200_OK)

    @extend_schema(
        parameters=[
            OpenApiParameter(
                name='Idempotency-Key',
                type=str,
                location=OpenApiParameter.HEADER,
                required=True,
                description='Unique key generated by client to ensure retry-safe creation.'
            )
        ],
        request=PatientCreateSerializer,
        responses={201: PatientSerializer},
        description="Create a new patient record with mandatory Idempotency-Key protection."
    )
    @idempotent_action(endpoint='/api/patients/')
    def create(self, request):
        serializer = PatientCreateSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        patient = PatientService.create_patient(
            user=request.user,
            data=serializer.validated_data
        )
        return Response(
            {"success": True, "data": PatientSerializer(patient).data},
            status=status.HTTP_201_CREATED
        )

    @extend_schema(
        request=PatientUpdateSerializer,
        responses={200: PatientSerializer},
        description="Update a patient record with optimistic locking. Client must provide 'version'."
    )
    def update(self, request, pk=None):
        patient = PatientService.get_patient(user=request.user, patient_id=int(pk))
        self.check_object_permissions(request, patient)

        serializer = PatientUpdateSerializer(instance=patient, data=request.data)
        serializer.is_valid(raise_exception=True)
        expected_version = serializer.validated_data.pop('version')

        updated_patient = PatientService.update_patient(
            user=request.user,
            patient_id=int(pk),
            data=serializer.validated_data,
            expected_version=expected_version
        )
        return Response(
            {"success": True, "data": PatientSerializer(updated_patient).data},
            status=status.HTTP_200_OK
        )

    def partial_update(self, request, pk=None):
        return self.update(request, pk)

    @extend_schema(
        responses={204: None},
        description="Delete a patient record (creator only)."
    )
    def destroy(self, request, pk=None):
        patient = PatientService.get_patient(user=request.user, patient_id=int(pk))
        self.check_object_permissions(request, patient)
        PatientService.delete_patient(user=request.user, patient_id=int(pk))
        return Response(
            {"success": True, "message": "Patient record deleted successfully."},
            status=status.HTTP_200_OK
        )
