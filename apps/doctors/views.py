from rest_framework import viewsets, status
from rest_framework.response import Response
from rest_framework.permissions import IsAuthenticated
from drf_spectacular.utils import extend_schema, OpenApiParameter

from apps.doctors.serializers import (
    DoctorSerializer,
    DoctorCreateSerializer,
    DoctorUpdateSerializer
)
from apps.doctors.services import DoctorService
from apps.doctors.permissions import IsDoctorCreatorOrReadOnly
from common.idempotency.services import idempotent_action


class DoctorViewSet(viewsets.ViewSet):
    """
    ViewSet for Doctor resources:
    - View: Any authenticated user
    - Create: Any authenticated user (Idempotent POST)
    - Update/Delete: Doctor creator only (Optimistic locking)
    """
    permission_classes = [IsAuthenticated, IsDoctorCreatorOrReadOnly]

    @extend_schema(
        responses={200: DoctorSerializer(many=True)},
        description="Retrieve all registered doctors."
    )
    def list(self, request):
        doctors = DoctorService.list_doctors(user=request.user)
        serializer = DoctorSerializer(doctors, many=True)
        return Response({"success": True, "data": serializer.data}, status=status.HTTP_200_OK)

    @extend_schema(
        responses={200: DoctorSerializer},
        description="Retrieve details for a specific doctor."
    )
    def retrieve(self, request, pk=None):
        doctor = DoctorService.get_doctor(user=request.user, doctor_id=int(pk))
        self.check_object_permissions(request, doctor)
        serializer = DoctorSerializer(doctor)
        return Response({"success": True, "data": serializer.data}, status=status.HTTP_200_OK)

    @extend_schema(
        parameters=[
            OpenApiParameter(
                name='Idempotency-Key',
                type=str,
                location=OpenApiParameter.HEADER,
                required=True,
                description='Unique key generated by client to ensure retry-safe creation.'
            )
        ],
        request=DoctorCreateSerializer,
        responses={201: DoctorSerializer},
        description="Register a new doctor profile with Idempotency-Key protection."
    )
    @idempotent_action(endpoint='/api/doctors/')
    def create(self, request):
        serializer = DoctorCreateSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        doctor = DoctorService.create_doctor(
            user=request.user,
            data=serializer.validated_data
        )
        return Response(
            {"success": True, "data": DoctorSerializer(doctor).data},
            status=status.HTTP_201_CREATED
        )

    @extend_schema(
        request=DoctorUpdateSerializer,
        responses={200: DoctorSerializer},
        description="Update doctor profile with optimistic locking. Requires 'version'."
    )
    def update(self, request, pk=None):
        doctor = DoctorService.get_doctor(user=request.user, doctor_id=int(pk))
        self.check_object_permissions(request, doctor)

        serializer = DoctorUpdateSerializer(instance=doctor, data=request.data)
        serializer.is_valid(raise_exception=True)
        expected_version = serializer.validated_data.pop('version')

        updated = DoctorService.update_doctor(
            user=request.user,
            doctor_id=int(pk),
            data=serializer.validated_data,
            expected_version=expected_version
        )
        return Response({"success": True, "data": DoctorSerializer(updated).data}, status=status.HTTP_200_OK)

    def partial_update(self, request, pk=None):
        return self.update(request, pk)

    @extend_schema(
        responses={200: None},
        description="Delete a doctor profile (creator only)."
    )
    def destroy(self, request, pk=None):
        doctor = DoctorService.get_doctor(user=request.user, doctor_id=int(pk))
        self.check_object_permissions(request, doctor)
        DoctorService.delete_doctor(user=request.user, doctor_id=int(pk))
        return Response(
            {"success": True, "message": "Doctor profile deleted successfully."},
            status=status.HTTP_200_OK
        )
